// ============================================================================
// RxGuard — iCalendar (.ics) Routine Exporter
// Generates recurring daily calendar events for Morning, Afternoon, and
// Night pill routines to import directly into Apple, Google, and Outlook calendars.
// ============================================================================

import { Medication } from "@/types/analysis";

function formatIcsDate(date: Date): string {
  return date.toISOString().replace(/[-:]/g, "").split(".")[0] + "Z";
}

export function generateMedicationCalendarIcs(medications: Medication[]): string {
  const now = new Date();
  const dtstamp = formatIcsDate(now);

  const morningMeds = medications.filter((m) => m.schedule.morning);
  const afternoonMeds = medications.filter((m) => m.schedule.afternoon);
  const nightMeds = medications.filter((m) => m.schedule.night);

  const events: string[] = [];

  const createEvent = (
    slotName: string,
    hour: number,
    minute: number,
    meds: Medication[],
    uidSuffix: string
  ) => {
    if (meds.length === 0) return;

    const startDate = new Date();
    startDate.setHours(hour, minute, 0, 0);
    const endDate = new Date(startDate.getTime() + 15 * 60000); // 15 min duration

    const medSummary = meds
      .map((m) => `• ${m.name} (${m.raw_dosage}) - ${m.food_instruction} [${m.purpose}]`)
      .join("\\n");

    const eventIcs = [
      "BEGIN:VEVENT",
      `UID:rxguard-${uidSuffix}-${Date.now()}@rxguard.app`,
      `DTSTAMP:${dtstamp}`,
      `DTSTART:${formatIcsDate(startDate)}`,
      `DTEND:${formatIcsDate(endDate)}`,
      `RRULE:FREQ=DAILY;INTERVAL=1`,
      `SUMMARY:💊 RxGuard: ${slotName} (${meds.length} meds)`,
      `DESCRIPTION:Your scheduled medications:\\n\\n${medSummary}\\n\\nGenerated by RxGuard. Consult your doctor or pharmacist with questions.`,
      "STATUS:CONFIRMED",
      "BEGIN:VALARM",
      "TRIGGER:-PT5M",
      "ACTION:DISPLAY",
      `DESCRIPTION:Reminder: Time to take your ${slotName}`,
      "END:VALARM",
      "END:VEVENT",
    ].join("\r\n");

    events.push(eventIcs);
  };

  createEvent("Morning Medications", 8, 30, morningMeds, "morning");
  createEvent("Afternoon Medications", 13, 30, afternoonMeds, "afternoon");
  createEvent("Night Medications", 20, 30, nightMeds, "night");

  return [
    "BEGIN:VCALENDAR",
    "VERSION:2.0",
    "PRODID:-//RxGuard//Prescription & Lab Safety Decoder//EN",
    "CALSCALE:GREGORIAN",
    "METHOD:PUBLISH",
    "X-WR-CALNAME:RxGuard Medication Routine",
    "X-WR-TIMEZONE:UTC",
    events.join("\r\n"),
    "END:VCALENDAR",
  ].join("\r\n");
}
